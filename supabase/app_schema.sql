BEGIN;

CREATE TABLE IF NOT EXISTS public.users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  username text NOT NULL UNIQUE,
  email text NOT NULL UNIQUE,
  password text NOT NULL,
  first_name text,
  last_name text,
  phone text,
  shop_name text,
  logo text,
  google_id text,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.app_settings (
  key text PRIMARY KEY,
  value text
);

CREATE TABLE IF NOT EXISTS public.categories (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  family text NOT NULL DEFAULT 'autres'
);

CREATE TABLE IF NOT EXISTS public.products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  category text NOT NULL,
  brand text NOT NULL,
  model text NOT NULL,
  reference text,
  quantity integer NOT NULL DEFAULT 0,
  price_buy integer NOT NULL DEFAULT 0,
  price_sale integer NOT NULL DEFAULT 0,
  threshold integer NOT NULL DEFAULT 0,
  location text,
  description text,
  compatible_models text,
  date_created timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.sales (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_date timestamptz DEFAULT now(),
  total_amount integer DEFAULT 0,
  total_profit integer DEFAULT 0,
  items_count integer DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.sale_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id integer NOT NULL REFERENCES public.sales(id),
  product_id integer NOT NULL REFERENCES public.products(id),
  quantity integer NOT NULL,
  unit_price integer NOT NULL,
  subtotal integer NOT NULL,
  profit integer NOT NULL
);

CREATE TABLE IF NOT EXISTS public.stock_movements (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id integer NOT NULL REFERENCES public.products(id),
  type text NOT NULL,
  quantity integer NOT NULL,
  note text,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.user_sessions (
  sid varchar NOT NULL PRIMARY KEY,
  sess json NOT NULL,
  expire timestamp(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS user_sessions_expire_idx ON public.user_sessions (expire);

ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.app_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sales ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sale_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.stock_movements ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_sessions ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.users, public.app_settings, public.categories,
  public.products, public.sales, public.sale_items, public.stock_movements,
  public.user_sessions FROM PUBLIC, anon, authenticated;

REVOKE ALL ON SEQUENCE public.users_id_seq, public.categories_id_seq,
  public.products_id_seq, public.sales_id_seq, public.sale_items_id_seq,
  public.stock_movements_id_seq FROM PUBLIC, anon, authenticated;

DROP TABLE IF EXISTS public.afristock_usage;

COMMIT;
